package com.example.projectdnd.model.dto;

import lombok.Builder;
import lombok.Data;

/**
 * Data Transfer Object (DTO) containing the outcome of a spell or rune execution,
 * including dice roll results, mana consumption, and AI-generated narrative story.
 */
@Data
@Builder
public class ExecutionResultDto {
    /** Whether the spell or rune met or exceeded the required Difficulty Class (DC). */
    private boolean success;
    /** Summary message describing the mechanical outcome of the action. */
    private String message;
    /** Amount of mana consumed by the action. */
    private int manaSpent;
    /** Character's remaining mana after the action. */
    private int remainingMana;
    /** Result of the d20 dice roll. */
    private int diceRollResult;
    /** Atmospheric flavor text generated by the AI Dungeon Master (Storyteller). */
    private String narrativeStory;
}