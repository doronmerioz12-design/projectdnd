package com.example.projectdnd.model.enums;

/**
 * Enumeration of playable character classes (vocations) in Project DnD.
 */
public enum CharacterClass {
    /** A martial combatant who infuses weapons and armor with runic magic. */
    RUNE_WARRIOR,
    /** A hybrid spellcaster combining traditional wizardry with runic channeling. */
    RUNE_WIZARD,
    /** A scholarly arcane spellcaster specializing in predefined spells. */
    WIZARD,
    /** An elite practitioner who has mastered the ancient realms of runic power. */
    RUNE_MASTER,
    /** A novice magic user beginning their training in the arcane arts. */
    APPRENTICE
}