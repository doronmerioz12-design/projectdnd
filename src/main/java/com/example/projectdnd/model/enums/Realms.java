/**
 * Enumeration of elemental and metaphysical realms from which runes draw their power.
 */
public enum Realms {
    /** The elemental realm of heat, flame, and destruction. */
    FIRE,
    /** The elemental realm of tides, frost, and fluidity. */
    WATER,
    /** The elemental realm of stone, stability, and nature. */
    EARTH,
    /** The elemental realm of wind, storms, and sky. */
    AIR,
    /** The metaphysical realm of sleep, illusions, and the subconscious. */
    DREAMING,
    /** The metaphysical realm of passions, empathy, and mental influence. */
    EMOTIONS,
    /** The metaphysical realm of entropy, shadow, and the afterlife. */
    DEATH,
    /** The metaphysical realm of vitality, healing, and growth. */
    LIFE,
    /** The fundamental realm governing matter, time, and physical laws. */
    REALITY,
    /** The cosmic realm of starlight, space, and planar travel. */
    ASTRAL
}
